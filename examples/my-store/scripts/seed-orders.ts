// Dev seed for the private `order` type (src/content-types/order): two orders written through the server API
// (PrivateEntriesService), which may set the readOnly `items` and `total` and stores each generated placeholder PDF
// invoice as a private file (assets.local.privateRoot, never served at /media; download it from the order in the
// admin). Orders are never published and never reach /api/content.
// Run after `opencloudcms migrate:up`:  pnpm seed:orders
// An order whose code already exists is left untouched, unless --force (`pnpm seed:orders -- --force`): then it is
// deleted (with its private invoice) and created again.
import 'reflect-metadata';
import * as fs from 'node:fs';
import * as path from 'node:path';
import { Module } from '@nestjs/common';
import { NestFactory } from '@nestjs/core';

const root = path.resolve(__dirname, '..');
const force = process.argv.includes('--force');
const envFile = path.join(root, '.env');
if (fs.existsSync(envFile)) process.loadEnvFile(envFile);

/** A one-page PDF showing `lines` (Helvetica), with a valid cross-reference table. */
function placeholderPdf(lines: string[]): Buffer {
  const esc = (s: string) => s.replace(/[\\()]/g, (c) => `\\${c}`).replace(/[^\x20-\x7e]/g, '?');
  const text = lines.map((l, i) => `BT /F1 ${i === 0 ? 18 : 12} Tf 72 ${760 - i * 24} Td (${esc(l)}) Tj ET`).join('\n');
  const objects = [
    '<< /Type /Catalog /Pages 2 0 R >>',
    '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
    '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>',
    `<< /Length ${Buffer.byteLength(text, 'latin1')} >>\nstream\n${text}\nendstream`,
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
  ];
  let out = '%PDF-1.4\n';
  const offsets: number[] = [];
  objects.forEach((body, i) => {
    offsets.push(Buffer.byteLength(out, 'latin1'));
    out += `${i + 1} 0 obj\n${body}\nendobj\n`;
  });
  const xref = Buffer.byteLength(out, 'latin1');
  out += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  for (const o of offsets) out += `${String(o).padStart(10, '0')} 00000 n \n`;
  out += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF\n`;
  return Buffer.from(out, 'latin1');
}

async function main() {
  // Imported after .env is loaded: opencloudcms.config.ts reads DATABASE_URL.
  const { OpenCloudCmsModule, PrivateEntriesService } = await import('@opencloudcms/core');
  const { default: config } = await import('../opencloudcms.config');
  const { contentTypes } = await import('../src/generated');

  @Module({
    imports: [
      OpenCloudCmsModule.forRoot({
        root,
        config,
        contentTypes,
        web: { enabled: false },
        schemaEditable: false,
        // Same storage as src/app.module.ts: private files go to private-assets/ next to assets/.
        assets: { provider: 'local', local: { root: path.join(root, 'assets'), publicBaseUrl: '/media' } },
      }),
    ],
  })
  class SeedModule {}

  const app = await NestFactory.createApplicationContext(SeedModule, { logger: ['error'] });
  try {
    const orders = app.get(PrivateEntriesService);
    const samples = [
      {
        code: 'MS-1001',
        orderStatus: 'paid',
        items: [
          { sku: 'linen-shirt', name: 'Linen shirt', quantity: 1, price: { amount: 390000, currency: 'VND' } },
          { sku: 'canvas-tote', name: 'Canvas tote', quantity: 2, price: { amount: 150000, currency: 'VND' } },
        ],
        total: { amount: 690000, currency: 'VND' },
      },
      {
        code: 'MS-1002',
        orderStatus: 'pending',
        items: [{ sku: 'canvas-tote', name: 'Canvas tote', quantity: 1, price: { amount: 150000, currency: 'VND' } }],
        total: { amount: 150000, currency: 'VND' },
      },
    ];
    for (const o of samples) {
      const found = (await orders.list('order', { filter: { code: o.code }, limit: 1 })).data[0];
      if (found && !force) {
        console.log(`skip order ${o.code}: it already exists (--force replaces it)`);
        continue;
      }
      if (found) await orders.remove('order', found.documentId as string);
      const lines = [
        `my-store - invoice ${o.code}`,
        ...o.items.map((i) => `${i.quantity} x ${i.name}  ${i.price.amount.toLocaleString('en-US')} ${i.price.currency}`),
        `Total: ${o.total.amount.toLocaleString('en-US')} ${o.total.currency}`,
        'Placeholder invoice generated by scripts/seed-orders.ts',
      ];
      const invoice = { buffer: placeholderPdf(lines), filename: `invoice-${o.code}.pdf`, contentType: 'application/pdf' };
      const { data } = await orders.create('order', { ...o, invoice });
      console.log(`${found ? 'replaced' : 'created'} order ${o.code} (${data.documentId}, invoice ${data.invoice})`);
    }
  } finally {
    await app.close();
  }
}

main().catch((e: unknown) => {
  console.error(e);
  process.exit(1);
});
