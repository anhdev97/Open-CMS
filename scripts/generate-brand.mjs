import { readFileSync, writeFileSync } from 'node:fs';

// Embed approved SVGs so installed admin packages need no host public-directory setup.
const assets = {
  logoColor: 'svg/logo-horizontal-color.svg',
  logoDark: 'svg/logo-horizontal-dark.svg',
  favicon: 'favicon/favicon.svg',
};
const lines = Object.entries(assets).map(([name, file]) => {
  const svg = readFileSync(new URL(`../brand/${file}`, import.meta.url), 'utf8');
  return `export const ${name} = ${JSON.stringify(`data:image/svg+xml,${encodeURIComponent(svg)}`)};`;
});
writeFileSync(new URL('../packages/core/admin/src/brand.ts', import.meta.url),
  '// Generated by scripts/generate-brand.mjs; edit brand/svg or brand/favicon, then regenerate.\n' + lines.join('\n') + '\n');
