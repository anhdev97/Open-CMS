import { printStatement } from './ddl';
import type { MigrationPlan } from './plan';

export function migrationStamp(date = new Date()): string {
  const p = (n: number) => String(n).padStart(2, '0');
  return `${date.getUTCFullYear()}${p(date.getUTCMonth() + 1)}${p(date.getUTCDate())}${p(date.getUTCHours())}${p(date.getUTCMinutes())}${p(date.getUTCSeconds())}`;
}

export function slugifyMigrationName(name: string): string {
  return (
    name
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '_')
      .replace(/^_+|_+$/g, '')
      .slice(0, 60) || 'schema_change'
  );
}

/** Suggests a readable migration name from the plan summary. */
export function suggestMigrationName(plan: MigrationPlan): string {
  if (plan.summary.length === 1) return slugifyMigrationName(plan.summary[0]);
  return slugifyMigrationName(`${plan.summary[0]} and ${plan.summary.length - 1} more`);
}

export function renderMigrationFile(plan: MigrationPlan, meta: { name: string; generatedAt: string }): string {
  const header = [
    '/**',
    ` * ${meta.name}`,
    ' *',
    ' * Generated by opencms-cli. Review it, edit it if you need data migrations,',
    ' * then commit it together with src/content-types and migrations/_snapshot.json.',
    ' *',
    ...plan.summary.map((s) => ` *   - ${s}`),
    ...(plan.warnings.length ? [' *', ' * Warnings:', ...plan.warnings.map((w) => ` *   ! ${w}`)] : []),
    ' */',
  ];
  const body = (stmts: MigrationPlan['up']) =>
    stmts.length ? stmts.map((s) => printStatement(s)).join('\n\n') : '  // nothing to do';
  return `${header.join('\n')}
import { Kysely, sql } from 'kysely';

export const meta = ${JSON.stringify({ generatedAt: meta.generatedAt, summary: plan.summary }, null, 2)};

export async function up(db: Kysely<any>): Promise<void> {
${body(plan.up)}
}

export async function down(db: Kysely<any>): Promise<void> {
${body(plan.down)}
}
`;
}
